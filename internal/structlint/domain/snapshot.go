package domain

// Entry — узел снимка дерева проекта: относительный путь и признак каталога. Содержимое файла
// в снимок не входит — линтер читает только имена и пути (SEC, secrets safety).
type Entry struct {
	// Path — относительный путь от корня проекта с прямыми слэшами (`/`).
	Path string
	// IsDir — признак каталога.
	IsDir bool
}

// TreeSnapshot — снимок дерева файлов проекта, над которым работает ядро проверки. Проверка
// зависит только от снимка и правил эталона и не зависит от порядка обхода или окружения.
type TreeSnapshot struct {
	// Root — корневой путь проекта, от которого построены относительные пути записей.
	Root string
	// Entries — записи дерева (файлы и каталоги), относительные пути.
	Entries []Entry
}
